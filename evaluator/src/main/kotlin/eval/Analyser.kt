package eval

import java.io.File

// ── Data model ───────────────────────────────────────────────────────────────

data class FileResult(
    val javaPath: String,
    val ktPath: String,
    val conversionFailed: Boolean,
    val lineCountJava: Int,
    val lineCountKt: Int,
    val lineRatio: Double,           // kt/java — lower = more concise
    val nullBangCount: Int,          // !! occurrences (unsafe assertions — bad)
    val getterSetterCount: Int,      // Java-style getX() / setX() survivors
    val companionObjectCount: Int,   // evidence of static member migration
    val dataClassCount: Int,         // data class declarations
    val varUsageCount: Int,          // var vs val — prefer val
    val valUsageCount: Int,
    val javaImportsCount: Int,       // leftover java.* imports
    val syntheticAccessorCount: Int, // access$NNN patterns from j2k
    val idiomaticScore: Int,         // 0–100 composite
    val checks: List<CheckResult>,
)

data class CheckResult(
    val name: String,
    val passed: Boolean,
    val detail: String,
)

data class Summary(
    val totalFiles: Int,
    val conversionFailures: Int,
    val compiledCount: Int,
    val avgIdiomaticScore: Double,
    val avgLineRatio: Double,
    val totalNullBangs: Int,
    val totalGetterSetters: Int,
)

// ── File collection ──────────────────────────────────────────────────────────

fun collectFilePairs(originalDir: File, convertedDir: File): List<Pair<File, File>> {
    return originalDir
        .walkTopDown()
        .filter { it.extension == "java" }
        .mapNotNull { javaFile ->
            val rel = javaFile.relativeTo(originalDir).path
            val ktRel = rel.removeSuffix(".java") + ".kt"
            val ktFile = File(convertedDir, ktRel)
            if (ktFile.exists()) javaFile to ktFile else null
        }
        .toList()
}

// ── Manifest ────────────────────────────────────────────────────────────────

data class Manifest(val total: Int, val success: Int, val failed: Int)

fun readManifest(convertedDir: File): Manifest {
    val f = File(convertedDir, ".j2k_manifest.txt")
    if (!f.exists()) return Manifest(0, 0, 0)
    val map = f.readLines()
        .filter { '=' in it }
        .associate { line -> line.substringBefore('=') to line.substringAfter('=') }
    return Manifest(
        total   = map["total"]?.toIntOrNull()   ?: 0,
        success = map["success"]?.toIntOrNull() ?: 0,
        failed  = map["failed"]?.toIntOrNull()  ?: 0,
    )
}

// ── Per-file analysis ────────────────────────────────────────────────────────

fun analyseFilePair(javaFile: File, ktFile: File, edgeMode: Boolean): FileResult {
    val javaLines = javaFile.readLines()
    val ktLines   = ktFile.readLines()
    val ktText    = ktFile.readText()
    val javaText  = javaFile.readText()

    val conversionFailed = ktLines.firstOrNull()
        ?.startsWith("// J2K_CONVERSION_FAILED") == true

    // ── Raw counts ───────────────────────────────────────────────────────────
    val lineCountJava = javaLines.size
    val lineCountKt   = ktLines.size
    val lineRatio     = if (lineCountJava > 0) lineCountKt.toDouble() / lineCountJava else 1.0

    // !! — unsafe non-null assertions left by j2k (indicates nullable issues)
    val nullBangCount = "!!".toRegex().findAll(ktText).count()

    // Java-style getter/setter survivors: fun getX() / fun setX(
    val getterSetterCount = """fun\s+(get|set)[A-Z]\w*\s*\(""".toRegex()
        .findAll(ktText).count()

    // companion object { — evidence static fields were migrated
    val companionObjectCount = """companion\s+object""".toRegex()
        .findAll(ktText).count()

    // data class declarations
    val dataClassCount = """data\s+class\s+""".toRegex()
        .findAll(ktText).count()

    // var vs val (prefer val — immutability)
    val varUsageCount = """\bvar\b""".toRegex().findAll(ktText).count()
    val valUsageCount = """\bval\b""".toRegex().findAll(ktText).count()

    // Leftover java.* imports (excluding java.time, java.util etc that Kotlin uses too)
    // Specifically flag: java.util.ArrayList, java.util.HashMap — should be listOf/mapOf
    val javaImportsCount = """import java\.(util\.(ArrayList|HashMap|LinkedList|HashSet)|lang\.(StringBuilder))"""
        .toRegex().findAll(ktText).count()

    // Synthetic accessors generated by j2k for Java private-field access from inner classes
    val syntheticAccessorCount = """access\$\d+""".toRegex().findAll(ktText).count()

    // ── Per-check results ────────────────────────────────────────────────────
    val checks = mutableListOf<CheckResult>()

    checks += CheckResult(
        name   = "conversion_succeeded",
        passed = !conversionFailed,
        detail = if (conversionFailed) "j2k failed to convert this file" else "OK",
    )

    checks += CheckResult(
        name   = "no_unsafe_assertions",
        passed = nullBangCount == 0,
        detail = if (nullBangCount > 0) "$nullBangCount !! found — null safety not preserved" else "OK",
    )

    checks += CheckResult(
        name   = "no_getter_setter_survivors",
        passed = getterSetterCount == 0,
        detail = if (getterSetterCount > 0) "$getterSetterCount Java-style accessors not converted" else "OK",
    )

    checks += CheckResult(
        name   = "line_count_reduced",
        passed = lineRatio < 1.05,
        detail = "Kotlin/Java line ratio: ${"%.2f".format(lineRatio)}",
    )

    checks += CheckResult(
        name   = "prefers_val_over_var",
        passed = valUsageCount >= varUsageCount,
        detail = "val=$valUsageCount var=$varUsageCount",
    )

    checks += CheckResult(
        name   = "no_java_collection_imports",
        passed = javaImportsCount == 0,
        detail = if (javaImportsCount > 0) "$javaImportsCount redundant java.util collection imports" else "OK",
    )

    checks += CheckResult(
        name   = "no_synthetic_accessors",
        passed = syntheticAccessorCount == 0,
        detail = if (syntheticAccessorCount > 0) "$syntheticAccessorCount access\$ patterns found" else "OK",
    )

    // ── Idiomatic score (0–100) ──────────────────────────────────────────────
    // Weighted: conversion (40) + null safety (20) + style (40)
    val idiomaticScore = when {
        conversionFailed -> 0
        else -> {
            var score = 100

            // Deduct for null bangs (up to -20)
            score -= minOf(nullBangCount * 2, 20)

            // Deduct for getter/setter survivors (up to -20)
            score -= minOf(getterSetterCount * 4, 20)

            // Deduct for bad val/var ratio (up to -10)
            if (varUsageCount > valUsageCount) score -= 10

            // Deduct for redundant java imports (-5 each, up to -15)
            score -= minOf(javaImportsCount * 5, 15)

            // Deduct for synthetic accessors (-5 each, up to -10)
            score -= minOf(syntheticAccessorCount * 5, 10)

            // Deduct if file grew instead of shrank (up to -10)
            if (lineRatio > 1.1) score -= 10
            else if (lineRatio > 1.05) score -= 5

            maxOf(score, 0)
        }
    }

    return FileResult(
        javaPath             = javaFile.path,
        ktPath               = ktFile.path,
        conversionFailed     = conversionFailed,
        lineCountJava        = lineCountJava,
        lineCountKt          = lineCountKt,
        lineRatio            = lineRatio,
        nullBangCount        = nullBangCount,
        getterSetterCount    = getterSetterCount,
        companionObjectCount = companionObjectCount,
        dataClassCount       = dataClassCount,
        varUsageCount        = varUsageCount,
        valUsageCount        = valUsageCount,
        javaImportsCount     = javaImportsCount,
        syntheticAccessorCount = syntheticAccessorCount,
        idiomaticScore       = idiomaticScore,
        checks               = checks,
    )
}

// ── Summary aggregation ──────────────────────────────────────────────────────

fun buildSummary(manifest: Manifest, results: List<FileResult>, edgeMode: Boolean): Summary {
    val failed    = results.count { it.conversionFailed }
    val succeeded = results.filter { !it.conversionFailed }
    return Summary(
        totalFiles          = results.size,
        conversionFailures  = failed,
        compiledCount       = succeeded.size,  // proxy — actual compile check requires kotlinc
        avgIdiomaticScore   = if (succeeded.isEmpty()) 0.0 else succeeded.map { it.idiomaticScore.toDouble() }.average(),
        avgLineRatio        = if (succeeded.isEmpty()) 0.0 else succeeded.map { it.lineRatio }.average(),
        totalNullBangs      = results.sumOf { it.nullBangCount },
        totalGetterSetters  = results.sumOf { it.getterSetterCount },
    )
}
